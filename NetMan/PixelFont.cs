namespace NetMan;

// A tiny 3 x 5 bitmap font keeps HUD text sharp at the same scale as the sprites.
internal static class PixelFont
{
  private static readonly Dictionary<char, string> Glyphs = new()
  {
    ['A'] = "010101111101101",
    ['B'] = "110101110101110",
    ['C'] = "011100100100011",
    ['D'] = "110101101101110",
    ['E'] = "111100110100111",
    ['F'] = "111100110100100",
    ['G'] = "011100101101011",
    ['H'] = "101101111101101",
    ['I'] = "111010010010111",
    ['J'] = "001001001101010",
    ['K'] = "101101110101101",
    ['L'] = "100100100100111",
    ['M'] = "101111111101101",
    ['N'] = "101111111111101",
    ['O'] = "010101101101010",
    ['P'] = "110101110100100",
    ['Q'] = "010101101111011",
    ['R'] = "110101110101101",
    ['S'] = "011100010001110",
    ['T'] = "111010010010010",
    ['U'] = "101101101101111",
    ['V'] = "101101101101010",
    ['W'] = "101101111111101",
    ['X'] = "101101010101101",
    ['Y'] = "101101010010010",
    ['Z'] = "111001010100111",
    ['0'] = "111101101101111",
    ['1'] = "010110010010111",
    ['2'] = "110001010100111",
    ['3'] = "110001010001110",
    ['4'] = "101101111001001",
    ['5'] = "111100110001110",
    ['6'] = "011100111101111",
    ['7'] = "111001010010010",
    ['8'] = "111101111101111",
    ['9'] = "111101111001110",
    [':'] = "000010000010000",
    ['-'] = "000000111000000",
    ['/'] = "001001010100100",
    ['!'] = "010010010000010",
    ['.'] = "000000000000010",
    ['?'] = "110001010000010",
    ['+'] = "000010111010000",
    ['\''] = "010010000000000",
  };

  public static void Draw(PixelBuffer frame, string text, int x, int y, uint color, int scale = 1)
  {
    foreach (char character in text.ToUpperInvariant())
    {
      if (Glyphs.TryGetValue(character, out string? bits))
      {
        for (int row = 0; row < 5; row++)
        {
          for (int col = 0; col < 3; col++)
          {
            if (bits[(row * 3) + col] == '1')
              frame.Fill(x + (col * scale), y + (row * scale), scale, scale, color);
          }
        }
      }

      x += 4 * scale;
    }
  }
}
